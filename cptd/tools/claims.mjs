// Turns one area's content into files for fresh checker agents. Run from the repo root:
//
//   node cptd/tools/claims.mjs <area>                      writes research/<dN>/claims-<area>.md
//   node cptd/tools/claims.mjs <area> --cold               writes research/<dN>/cold-<area>.md
//   node cptd/tools/claims.mjs <area> --compare <answers>  prints disagreements with the keys
//   add  --out <dir>  to write somewhere other than research/<dN>/
//
// claims: a numbered list of atomic claims (one fact per line), each with a stable id
//   naming its source, e.g. [kirkpatrick.items.2.name] or [q-roi-1.key].
// cold: the area's questions and case steps with no keys, flags or explanations, plus
//   the answer format at the top.
// compare: reads answers in that format and prints only disagreements and
//   "two defensible" flags, with the keyed answer next to the agent's.
import fs from 'node:fs';
import path from 'node:path';
import { loadContent, appDir } from './load-content.mjs';

const args = process.argv.slice(2);
const opt = (name) => { const i = args.indexOf(name); if (i < 0) return null; const v = args[i + 1]; args.splice(i, 2); return v; };
const flag = (name) => { const i = args.indexOf(name); if (i < 0) return false; args.splice(i, 1); return true; };
const outDir = opt('--out');
const compareFile = opt('--compare');
const cold = flag('--cold');
const areaId = args[0];

const { C } = loadContent();
const A = C.areas.find((a) => a.id === areaId);
if (!A) {
  console.log('Usage: node cptd/tools/claims.mjs <area> [--cold | --compare <answers.md>] [--out <dir>]');
  console.log(`Areas: ${C.areas.map((a) => `${a.id} (${a.domain})`).join(', ')}`);
  process.exit(2);
}
const D = C.domains.find((d) => d.id === A.domain);
const STMT_AREA = {};
C.areas.forEach((a) => a.stmts.forEach((s) => { STMT_AREA[s] = a.id; }));
const models = C.models.filter((m) => m.area === A.id);
const questions = C.questions.filter((q) => STMT_AREA[q.stmt] === A.id);
const cases = C.cases.filter((c) => STMT_AREA[(c.stmts || [])[0]] === A.id);
const LET = ['A', 'B', 'C', 'D', 'E', 'F'];
const one = (s) => String(s == null ? '' : s).replace(/\s+/g, ' ').trim();
const q_ = (s) => `“${one(s)}”`;
const stmtLabel = (s) => `${s} (${one(C.statements[s])})`;
const pl = (n, w) => `${n} ${w}${n === 1 ? '' : 's'}`;
// The cold test shows options in a fixed shuffled order per item (authors tend to key
// option A), so the position gives nothing away. perm[k] = stored index shown at k.
function perm(id, n) {
  let h = 2166136261;
  for (const ch of id) { h ^= ch.charCodeAt(0); h = Math.imul(h, 16777619) >>> 0; }
  const rnd = () => { h = (h + 0x6D2B79F5) >>> 0; let t = h; t = Math.imul(t ^ (t >>> 15), t | 1); t ^= t + Math.imul(t ^ (t >>> 7), t | 61); return ((t ^ (t >>> 14)) >>> 0) / 4294967296; };
  const a = Array.from({ length: n }, (_, i) => i);
  for (let i = n - 1; i > 0; i--) { const j = Math.floor(rnd() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; }
  return a;
}
const dir = outDir || path.join(appDir, 'research', D.id);
const header = (kind) => [
  `# ${kind}: ${A.id}, ${A.name} (Domain ${D.num}: ${D.name})`,
  '',
  `Generated by \`node cptd/tools/claims.mjs ${A.id}${kind === 'Cold test' ? ' --cold' : ''}\` from content version ${C.version}. Don't edit by hand; fix the content file and run it again.`,
  '',
  `Statements: ${A.stmts.map(stmtLabel).join('; ')}.`,
  '',
  `${pl(models.length, 'model')}, ${pl(questions.length, 'question')}, ${pl(cases.length, 'case')}.`,
  '',
];

/* ---------------- claims ---------------- */
function claims() {
  const out = [];
  const add = (id, text) => out.push([id, one(text)]);
  for (const m of models) {
    const N = m.name;
    add(`${m.id}.name`, `The model with id ${m.id} is called ${q_(N)} (short name ${q_(m.short)}).`);
    add(`${m.id}.who`, `${N} comes from ${m.who}.`);
    add(`${m.id}.tag`, `${N} is labeled ${q_(C.tags[m.tag] || m.tag)}.`);
    add(`${m.id}.src`, `The source for ${N} is: ${m.src}`);
    (m.stmts || []).forEach((s, k) => add(`${m.id}.stmt.${k + 1}`, `${N} belongs under exam statement ${stmtLabel(s)}.`));
    if (m.kind === 'ordered') add(`${m.id}.kind`, `${N} has ${m.items.length} ${m.unit} in a fixed order, ${m.orderNote}.`);
    else add(`${m.id}.kind`, `${N} has ${m.items.length} ${m.unit}, in no particular order.`);
    m.items.forEach((it, k) => {
      const p = `${m.id}.items.${k + 1}`;
      add(`${p}.name`, `${q_(it.t)} is one of the ${m.unit} of ${N}.`);
      if (m.kind === 'ordered') add(`${p}.order`, `In ${N}, ${q_(it.t)} is number ${k + 1} of ${m.items.length} (${m.orderNote}).`);
      add(`${p}.desc`, `In ${N}, ${q_(it.t)} means: ${it.d}`);
    });
    (m.groups || []).forEach((g, gi) => g.m.forEach((x, k) => add(`${m.id}.groups.${gi + 1}.${k + 1}`, `In ${N}, ${q_(x)} falls under the heading ${q_(g.t)}.`)));
    (m.decoys || []).forEach((d, k) => add(`${m.id}.decoys.${k + 1}`, `${q_(d)} is NOT one of the ${m.unit} of ${N}.`));
    add(`${m.id}.hook`, `Memory hook for ${N}: ${m.hook}`);
    add(`${m.id}.exam`, `How ${N} shows up on the exam: ${m.exam}`);
    if (m.note) add(`${m.id}.note`, `Worth knowing about ${N}: ${m.note}`);
  }
  for (const q of questions) {
    add(`${q.id}.stem`, `Question ${q.id} (statement ${q.stmt}${q.model ? `, model ${q.model}` : ''}) asks: ${q.q}`);
    q.o.forEach((o, k) => add(`${q.id}.${LET[k]}`, `Option ${LET[k]} of ${q.id}: ${o}`));
    add(`${q.id}.key`, `The one defensible answer to ${q.id} is ${LET[q.a]}: ${q_(q.o[q.a])}.`);
    add(`${q.id}.why`, `Explanation for ${q.id}: ${q.why}`);
  }
  for (const c of cases) {
    add(`${c.id}.setup`, `Case ${c.id} (${q_(c.title)}, statements ${(c.stmts || []).join(', ')}) setup: ${c.setup}`);
    c.steps.forEach((st, si) => {
      const p = `${c.id}.step-${si + 1}`;
      add(`${p}.text`, `Step ${si + 1} of ${c.id} asks: ${st.text}`);
      st.options.forEach((o, k) => add(`${p}.opt-${k + 1}`, `In step ${si + 1} of ${c.id}, ${q_(o[0])} is ${o[1] ? 'a RIGHT pick' : 'a WRONG pick'}.`));
      add(`${p}.why`, `Explanation for step ${si + 1} of ${c.id}: ${st.why}`);
    });
  }
  const lines = header('Claims').concat([
    'Each numbered line is one claim. The id in brackets names where it comes from (model, item, question or case step), so a fix can be found. Check every claim against the sources; report the ids of claims that are wrong, unsupported or misleading.',
    '',
  ], out.map(([id, t], k) => `${k + 1}. [${id}] ${t}`));
  return { lines, n: out.length };
}

/* ---------------- cold test ---------------- */
const FORMAT = [
  '## Answer format',
  '',
  'Answer from your own knowledge and the sources, not the app. Write one line per item, in a plain file (answers can be in any order):',
  '',
  '```',
  'q-id | B | ok',
  'q-id | B | two: B,C | why both fit',
  'case-id.step-1 | 1,3 | ok',
  'case-id.step-2 | 2 | two: 2,4 | option 4 is arguable',
  '```',
  '',
  '- Column 1: the item id exactly as shown below.',
  '- Column 2: for a question, the one letter you would pick; for a case step, the numbers of every option you would select (comma-separated, no spaces needed).',
  '- Column 3: `ok` if exactly one answer is defensible (for a case step: every option is clearly right or clearly wrong). Otherwise `two:` and the letters (or option numbers) that are each defensible.',
  '- Column 4 (optional): a short note.',
  '',
];
function coldTest() {
  const lines = header('Cold test').concat(FORMAT, ['## Questions', '']);
  for (const q of questions) {
    lines.push(`### ${q.id}`, '', `Statement ${stmtLabel(q.stmt)}`, '', one(q.q), '');
    perm(q.id, q.o.length).forEach((oi, k) => lines.push(`- ${LET[k]}. ${one(q.o[oi])}`));
    lines.push('');
  }
  if (cases.length) lines.push('## Case steps', '', 'Select every option that fits. On the exam, each right pick earns a point and each wrong pick loses one.', '');
  for (const c of cases) {
    lines.push(`### Case ${c.id}: ${one(c.title)}`, '', one(c.setup), '');
    c.steps.forEach((st, si) => {
      lines.push(`#### ${c.id}.step-${si + 1}`, '', one(st.text), '');
      perm(`${c.id}.step-${si + 1}`, st.options.length).forEach((oi, k) => lines.push(`${k + 1}. ${one(st.options[oi][0])}`));
      lines.push('');
    });
  }
  return { lines, n: questions.length + cases.reduce((n, c) => n + c.steps.length, 0) };
}

/* ---------------- compare ---------------- */
function compare(file) {
  const keyed = {};
  // Keys and answers are in the cold test's shown order (letters A-D, options 1-n).
  for (const q of questions) {
    const p = perm(q.id, q.o.length);
    const text = (x) => { const k = LET.indexOf(x); return k >= 0 && k < p.length ? ` ${q_(q.o[p[k]])}` : ''; };
    keyed[q.id] = { kind: 'q', key: LET[p.indexOf(q.a)], show: (x) => `${x}${text(x)}` };
  }
  for (const c of cases) c.steps.forEach((st, si) => {
    const id = `${c.id}.step-${si + 1}`; const p = perm(id, st.options.length);
    const key = p.map((oi, k) => (st.options[oi][1] ? k + 1 : 0)).filter(Boolean).join(',');
    keyed[id] = { kind: 'case', key, show: (x) => x || 'none' };
  });
  const normSet = (s) => s.split(/[\s,]+/).filter(Boolean).map(Number).sort((a, b) => a - b).join(',');
  const seen = new Set(); const report = []; const unknown = [];
  for (const raw of fs.readFileSync(file, 'utf8').split('\n')) {
    const cols = raw.replace(/^\s*[-*]\s+/, '').split('|').map((x) => x.trim());
    if (cols.length < 2 || !cols[0] || cols[0].startsWith('#') || cols[0].startsWith('```')) continue;
    const [id, ans, fl = '', ...rest] = cols;
    const k = keyed[id];
    if (!k) { if (/^[a-z0-9-]+(\.step-\d+)?$/i.test(id)) unknown.push(id); continue; }
    seen.add(id);
    const mine = k.kind === 'q' ? ans.toUpperCase() : normSet(ans);
    const note = rest.join(' | ');
    const two = /^two/i.test(fl);
    if (mine !== k.key) report.push(`DISAGREE ${id}: key ${k.show(k.key)} | agent ${k.show(mine)}${two ? ` | ${fl}` : ''}${note ? ` | ${note}` : ''}`);
    else if (two) report.push(`TWO      ${id}: key ${k.show(k.key)} | agent agrees, flags ${fl}${note ? ` | ${note}` : ''}`);
  }
  const missing = Object.keys(keyed).filter((id) => !seen.has(id));
  report.forEach((l) => console.log(l));
  console.log(`${A.id}: ${seen.size} of ${Object.keys(keyed).length} answered, ${report.filter((l) => l.startsWith('DISAGREE')).length} disagreements, ${report.filter((l) => l.startsWith('TWO')).length} two-defensible flags.`);
  if (missing.length) console.log(`not answered: ${missing.join(', ')}`);
  if (unknown.length) console.log(`unknown ids in the answers: ${unknown.join(', ')}`);
}

if (compareFile) compare(compareFile);
else {
  const { lines, n } = cold ? coldTest() : claims();
  fs.mkdirSync(dir, { recursive: true });
  const file = path.join(dir, `${cold ? 'cold' : 'claims'}-${A.id}.md`);
  fs.writeFileSync(file, lines.join('\n') + '\n');
  const rel = path.relative(process.cwd(), file);
  console.log(`wrote ${rel.startsWith('..') ? file : rel}: ${n} ${cold ? 'items' : 'claims'}`);
}
